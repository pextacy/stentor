"use client";

import QRCode from "qrcode";
import { useEffect, useState } from "react";
import { PictogramSvg } from "@/components/Pictogram";
import { type PublicAlert, getPublic } from "@/lib/api";

/** A one-page poster for doors, shelters and notice boards: every sendable language,
 *  the pictogram, and a QR code to the live public page (which shows updates and
 *  cancellations). Only sendable languages are ever printed. */
export default function PrintPoster({ params }: { params: { id: string } }) {
  const [data, setData] = useState<PublicAlert | null>(null);
  const [qr, setQr] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    getPublic(params.id, "en").then(setData).catch(() => setError("This alert could not be found."));
    const url = `${window.location.origin}/a/${params.id}`;
    QRCode.toString(url, { type: "svg", errorCorrectionLevel: "M", margin: 1, width: 160 })
      .then(setQr).catch(() => setQr(null));
  }, [params.id]);

  if (error) return <main className="p-6"><p role="alert" className="font-semibold text-blocked">{error}</p></main>;
  if (!data) return <main className="p-6"><p>Preparing poster…</p></main>;

  const url = typeof window === "undefined" ? "" : `${window.location.origin}/a/${data.id}`;
  return (
    <main className="poster mx-auto max-w-4xl bg-white px-6 py-6 print:max-w-none print:p-0">
      <style>{`@media print { header, nav, .no-print { display: none !important; } body { background: #fff !important; } .poster { font-size: 12pt; } @page { margin: 12mm; } }`}</style>
      <div className="no-print mb-4 flex flex-wrap items-center gap-3">
        <button type="button" onClick={() => window.print()} className="rounded-md border-2 border-ink bg-ink px-4 py-2 font-semibold text-white">Print</button>
        <a href={`/a/${data.id}`} className="underline">Back to the alert</a>
        <span className="text-sm text-slate-mute">{data.languages.length} languages, all verified or safe fallback.</span>
      </div>
      <div className="tape h-4" aria-hidden="true" />
      <div className="flex flex-wrap items-start gap-6 border-x-2 border-ink px-5 pt-4">
        <div className="min-w-0 flex-1">
          <h1 className="font-display text-5xl font-black uppercase tracking-wide text-blocked">
            {data.msg_type === "Cancel" ? "Alert cancelled" : "Emergency alert"}
          </h1>
          <p className="mt-1 text-sm text-slate-mute">Issued {new Date(data.created_at).toLocaleString()}{data.expires_at ? ` · until ${new Date(data.expires_at).toLocaleString()}` : ""}</p>
        </div>
        {qr && (
          <figure className="flex flex-col items-center">
            <div className="h-40 w-40" dangerouslySetInnerHTML={{ __html: qr }} role="img" aria-label={`QR code linking to ${url}`} />
            <figcaption className="mt-1 max-w-40 break-all text-center font-mono text-[10px]">{url}</figcaption>
          </figure>
        )}
      </div>
      <div className="flex justify-center border-x-2 border-ink px-5 py-3">
        <PictogramSvg intent={data.intent} places={data.places} times={data.times} />
      </div>
      <ol className="grid border-2 border-t-0 border-ink sm:grid-cols-2 print:grid-cols-2">
        {data.languages.map((l) => (
          <li key={l.lang} lang={l.lang} dir={l.dir} className="break-inside-avoid border-t-2 border-ink p-4 odd:sm:border-r-2 print:odd:border-r-2">
            <p className="text-xs font-bold uppercase tracking-widest text-slate-mute" dir="ltr">{l.name}</p>
            <p className="mt-1 text-lg leading-snug">{l.text}</p>
          </li>
        ))}
      </ol>
      <p className="mt-2 text-xs text-slate-mute">Demo poster generated by STENTOR. Not an official warning. Scan the code for updates.</p>
    </main>
  );
}
