"""CAP 1.2 (OASIS) XML export: one <info> per language.

Only VERIFIED and FALLBACK languages are included (docs/DOCS.md section 8).
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone

from stentor.channels.geo import CapArea, circle_text, polygon_text
from stentor.intent.schema import Action, AlertIntent, Hazard
from stentor.lock.locker import parse_time

NS = "urn:oasis:names:tc:emergency:cap:1.2"

CATEGORY = {
    Hazard.WILDFIRE: "Fire", Hazard.FLOOD: "Met", Hazard.EARTHQUAKE: "Geo", Hazard.TSUNAMI: "Geo",
    Hazard.HURRICANE: "Met", Hazard.TORNADO: "Met", Hazard.EXTREME_HEAT: "Met", Hazard.HAZMAT: "CBRNE",
    Hazard.SHOOTER: "Security", Hazard.BOIL_WATER: "Health", Hazard.OTHER: "Other",
}
RESPONSE = {
    Action.EVACUATE_NOW: "Evacuate", Action.PREPARE_TO_EVACUATE: "Prepare", Action.SHELTER_IN_PLACE: "Shelter",
    Action.MOVE_TO_HIGHER_GROUND: "Evacuate", Action.STAY_INDOORS: "Shelter", Action.AVOID_AREA: "Avoid",
    Action.BOIL_WATER: "Execute", Action.MONITOR: "Monitor", Action.ALL_CLEAR: "AllClear",
}
SEVERITY = {
    Action.EVACUATE_NOW: "Extreme", Action.SHELTER_IN_PLACE: "Extreme", Action.MOVE_TO_HIGHER_GROUND: "Extreme",
    Action.PREPARE_TO_EVACUATE: "Severe", Action.STAY_INDOORS: "Severe", Action.AVOID_AREA: "Severe",
    Action.BOIL_WATER: "Moderate", Action.MONITOR: "Minor", Action.ALL_CLEAR: "Minor",
}
CAP_STATUSES = ("Actual", "Exercise", "System", "Test", "Draft")
# STENTOR is not certified for production alerting (PRD section 7): never emit Actual.
ALLOWED_STATUSES = ("Exercise", "System", "Test", "Draft")
SENDABLE = ("VERIFIED", "FALLBACK", "APPROVED")
URGENCY = {"immediate": "Immediate", "expected": "Expected", "future": "Future"}
EVENT = {h: h.value.replace("_", " ").title() for h in Hazard}


def _iso(dt: datetime) -> str:
    # CAP requires an explicit offset and no fractional seconds; "Z" is not allowed.
    return dt.replace(microsecond=0).isoformat().replace("+00:00", "-00:00")


def _expires(intent: AlertIntent, mapping: dict[str, str], sent: datetime) -> str | None:
    """Turn the expiry literal into a CAP dateTime in the alert's time zone.
    A clock time already past today means tomorrow; a weekday alone means the end of
    that day. Unparseable expiry ("further notice") is left out rather than guessed."""
    if not intent.expires:
        return None
    p = parse_time(mapping.get(intent.expires, ""))
    if p is None:
        return None
    h, mi = (p.hour, p.minute) if p.hour is not None else (23, 59)
    exp = sent.replace(hour=h, minute=mi, second=0, microsecond=0)
    if p.weekday is not None:
        exp += timedelta(days=(p.weekday - sent.weekday()) % 7)
    elif p.day == "tomorrow":
        exp += timedelta(days=1)
    if exp <= sent:
        exp += timedelta(days=7 if p.weekday is not None else 1)
    return _iso(exp)


def _sub(parent: ET.Element, tag: str, text: str) -> ET.Element:
    el = ET.SubElement(parent, f"{{{NS}}}{tag}")
    el.text = text
    return el


def build_cap(alert_id: str, intent: AlertIntent, mapping: dict[str, str], source_text: str, results: list[dict],
              sent: datetime | None = None, sender: str = "stentor-demo@example.org", status: str = "Exercise",
              tz: timezone | None = None, sender_name: str = "STENTOR demo operator", web: str | None = None,
              msg_type: str = "Alert", references: list[tuple[str, str, datetime]] | None = None,
              area: CapArea | None = None) -> str:
    """status defaults to Exercise: STENTOR is not certified for production alerting.
    references: (sender, identifier, sent) of the alerts an Update or Cancel replaces."""
    if status not in ALLOWED_STATUSES:
        raise ValueError(f"CAP status '{status}' is not allowed; use one of {', '.join(ALLOWED_STATUSES)}")
    if msg_type not in ("Alert", "Update", "Cancel"):
        raise ValueError(f"unsupported msgType '{msg_type}'")
    if msg_type != "Alert" and not references:
        raise ValueError(f"a {msg_type} message must reference the alert it replaces")
    sent = (sent or datetime.now(tz or timezone.utc)).astimezone(tz or timezone.utc)
    ET.register_namespace("", NS)
    root = ET.Element(f"{{{NS}}}alert")
    _sub(root, "identifier", f"stentor-{alert_id}")
    _sub(root, "sender", sender)
    _sub(root, "sent", _iso(sent))
    _sub(root, "status", status)
    _sub(root, "msgType", msg_type)
    _sub(root, "scope", "Public")
    _sub(root, "note", "Generated by STENTOR. Each info block was verified by back parsing; see stentorStatus.")
    if references:
        _sub(root, "references", " ".join(f"{snd},stentor-{ident},{_iso(when.astimezone(sent.tzinfo))}" for snd, ident, when in references))

    places = [mapping[p] for p in dict.fromkeys(intent.area_refs) if p in mapping]
    area_desc = (area.desc if area and area.desc else None) or ", ".join(places) or "Area as described in the alert"
    expires = _expires(intent, mapping, sent)

    blocks = [{"lang": "en", "text": source_text, "status": "SOURCE", "renderer": "operator"}]
    blocks += [r for r in results if r["status"] in SENDABLE and r.get("text")]
    for b in blocks:
        info = ET.SubElement(root, f"{{{NS}}}info")
        _sub(info, "language", b["lang"])
        _sub(info, "category", CATEGORY[intent.hazard])
        _sub(info, "event", EVENT[intent.hazard])
        _sub(info, "responseType", RESPONSE[intent.action])
        _sub(info, "urgency", URGENCY.get(intent.urgency, "Unknown"))
        _sub(info, "severity", SEVERITY[intent.action])
        _sub(info, "certainty", "Observed" if intent.urgency == "immediate" else "Likely")
        if expires:
            _sub(info, "expires", expires)
        sentences = [s for s in b["text"].replace("\n", " ").split(". ") if s.strip()]
        _sub(info, "senderName", sender_name)
        # An empty source text must not crash the export; the event name is a safe headline.
        _sub(info, "headline", (sentences[0].strip().rstrip(".") if sentences else EVENT[intent.hazard])[:160])
        _sub(info, "description", b["text"])
        if len(sentences) > 1:
            _sub(info, "instruction", ". ".join(sentences[1:]))
        if web:
            _sub(info, "web", f"{web}?lang={b['lang']}")
        params = [("stentorStatus", b["status"]), ("stentorRenderer", b.get("renderer", ""))]
        if b.get("review"):
            params.append(("stentorReviewer", b["review"].get("reviewer", "")))
        for name, value in params:
            param = ET.SubElement(info, f"{{{NS}}}parameter")
            _sub(param, "valueName", name)
            _sub(param, "value", value)
        area_el = ET.SubElement(info, f"{{{NS}}}area")
        _sub(area_el, "areaDesc", area_desc)
        if area:
            for poly in area.polygons:
                _sub(area_el, "polygon", polygon_text(poly))
            for c in area.circles:
                _sub(area_el, "circle", circle_text(c))
            for g in area.geocodes:
                gc = ET.SubElement(area_el, f"{{{NS}}}geocode")
                _sub(gc, "valueName", g.name)
                _sub(gc, "value", g.value)

    ET.indent(root)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode")
